#!/usr/bin/perl
# يُدرج بندَ «شكرُ النعمة» العقديّ المعزوّ في صدر بطاقة «الضابط التربويّ واللغويّ» بلساني.
# العزو من النموذج المعتمد am-lisani (السعدي ص٤٤٥). آمنٌ للتكرار.
# الاستعمال: perl add-aqida-lisani.pl <file.html>   (فراغمة أو درس)
use strict; use warnings;
binmode STDOUT, ':raw';
my $f = shift or die "الاستعمال: perl add-aqida-lisani.pl <file>\n";
open my $x,'<:raw',$f or die "open $f: $!"; local $/; my $h=<$x>; close $x;

if ($h =~ /شكرُ النعمة:<\/b> اللسانُ وأدواتُ التعلّم/){ print "$f: مضافٌ سلفًا — يُخطّى\n"; exit }
unless ($h =~ /الضابط التربويّ واللغويّ/){ print "$f: لا ضابطَ لغويّ — يُخطّى\n"; exit }

my $li = '<li><b>شكرُ النعمة:</b> اللسانُ وأدواتُ التعلّم نعمةٌ من الله؛ نتعلّمها لنقرأ بها كلامَه ونشكرَه عليها.<span class="src">الدليل: ﴿وَجَعَلَ لَكُمُ السَّمْعَ وَالْأَبْصَارَ وَالْأَفْئِدَةَ لَعَلَّكُمْ تَشْكُرُونَ﴾ [النحل ٧٨]. المرجع: تيسير الكريم الرحمن للسعدي، ص٤٤٥.</span></li>';

# أدرِج بعد أوّل <ul class="steps"> يلي عنوان الضابط
unless ($h =~ s/(الضابط التربويّ واللغويّ<\/h2>.*?<div class="card"><ul class="steps">)/$1$li/s){
  die "$f: لم أجد بطاقة الضابط\n";
}
open my $o,'>:raw',$f or die "write $f: $!"; print $o $h; close $o;
print "$f: أُدرج البند العقديّ المعزوّ ✓\n";
